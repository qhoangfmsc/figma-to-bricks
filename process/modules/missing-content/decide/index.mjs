// DECISION ENGINE (autopilot). Turns the judgment calls the owner used to make one by one into deterministic rules over tree.json + facts.json,
// so that one Figma link is enough. Every decision is written down (decisions.md) with its reason and confidence, so the owner reviews the
// list afterwards instead of answering questions beforehand. It never invents content: URLs, alt texts, tooltip copy, form email recipients go to the
// designer list (designer-list.md) and the template is built with the safe default ('#', empty alt).
//
// Rules (all from owner decisions 2026-10-27, see policy.json):
//   flat-image candidate   a subtree with any visible text is NOT a picture (rejected); text-free decoration is approved
//   masked decoration      a text-free group with a mask layer is one picture rendered by Figma (CSS cannot mask like Figma)
//   accordion / tabs / menu / carousel candidates   approved by structure (2026-10-29): the content the Figma file does not draw (answers of closed FAQ items,
//                          panes of the other tabs, menu URLs, autoplay, the slider's item count) is asked in the Plan and applied from it; blank = empty, never invented.
//                          A slider is always loop. The dash count is the items, not the Figma pagination drawing.
//                          An accordion found only by its shape (no designer variants, no name) stays `proposed` and the Plan asks "is this an accordion?"
//   tooltip candidates     rejected: they need content only the designer has (listed as needs-review)
//   button candidate       approved, link '#' (designer list)
//   form candidate         approved when it has >= 2 input-like fields and a submit (real Bricks form; action / recipient / messages: designer list)
//   headings               text styles H1..H6 are honored; otherwise the largest text of the section is its title (h2, or h1 for the first section of
//                          the page); in a repeated group the largest text of each item is a title one level below
//   repeated groups        a container whose visible children are all the repeated items is a list (ul > li); a mixed container is left as blocks
//   icons (svg)            decorative: aria-hidden
//   images                 alt "" (decorative) and listed for the designer; eager in the first section, lazy below the fold
import { readFileSync } from 'node:fs';
import { PartKind, isKind, isAnyKind, isSignal, ListKind, isPaginationHint } from '../../recognize-parts/kinds.mjs';
import { decideCandidate } from './kind-decisions.mjs';
import { priceFrames, REGISTER_BUTTON_FIELDS, registerAttrKey } from '../../write-bricks/components/price-table.mjs';
import { compareFrames, BUY_BUTTON_FIELDS, buyAttrKey } from '../../write-bricks/components/compare-table.mjs';

const kids = (n) => (n.children ?? []).filter((c) => c.visible !== false);
const walk = (n, fn) => { if (n.visible === false) return; fn(n); kids(n).forEach((c) => walk(c, fn)); };
const find = (n, id) => { if (n.id === id) return n; for (const c of n.children ?? []) { const f = find(c, id); if (f) return f; } return null; };
const textsIn = (n) => { const out = []; walk(n, (m) => { if (m.type === 'TEXT' && !m.svg && m.text?.characters?.trim()) out.push(m); }); return out; };
const hasText = (n) => textsIn(n).length > 0;
const words = (s) => s.trim().split(/\s+/).length;
const NAV_SECTION = /^(menu|header|nav|navigation)\b/i;
const NAV_ITEM = /menu\s?item|nav\s?item|nav\s?link/i;
const DECOR_NAME = /glow|background|bg\b|pattern|decor|gradient|overlay|shadow|blur|border|corner|edge|line|divider/i;

export function decide(ws, { firstSection = false, variant = false, parentBg = null, formErrors = {}, namedOnly = false } = {}) {
  const tree = ws.readJson('tree.json');
  const facts = ws.readJson('facts.json');
  const det = ws.readJson('detections.json');
  const ov = ws.readJson('overrides.json', { nodes: {} });
  ov.nodes ??= {};
  for (const [id, v] of Object.entries(ov.nodes)) if (/^autopilot/i.test(v.reason ?? '')) delete ov.nodes[id]; // what an earlier run decided is regenerated by today's rules (like the detections)
  const decisions = [];
  const needs = []; // things the designer / owner may want to look at, never blocking
  const designer = [];
  const questions = []; // structured version of what the Plan (process/modules/missing-content/index.mjs) asks the owner: { group, node, label }
  const ask = (group, node, label, value) => { if (!questions.some((q) => q.group === group && q.node === node && !q.attr)) questions.push({ group, node, label, ...(value != null && value !== '' ? { value } : {}) }); };
  const askRegister = (node, fields = REGISTER_BUTTON_FIELDS, keyOf = registerAttrKey) => {
    for (const field of fields) {
      if (questions.some((q) => q.group === 'pattr' && q.node === node && q.attr === field.id)) continue;
      questions.push({ group: 'pattr', node, attr: field.id, key: keyOf(node, field.id), label: field.id, ...(field.value ? { value: field.value } : {}) });
    }
  };
  const log =(kind, node, decision, why, confidence = 'high') => decisions.push({ kind, node: node ? `${node.name} [${node.id}]` : '-', decision, why, confidence });
  const setOv = (id, patch) => { ov.nodes[id] = { ...(ov.nodes[id] ?? {}), ...patch, settings: { ...(ov.nodes[id]?.settings ?? {}), ...(patch.settings ?? {}) } }; if (!Object.keys(ov.nodes[id].settings).length) delete ov.nodes[id].settings; };
  const hand = new Set(Object.entries(ov.nodes).filter(([, v]) => v.reason && !/^autopilot/i.test(v.reason)).map(([k]) => k)); // owner's own entries win

  // ---- 0. a section without a visible fill of its own sits on its frame's fill in Figma (the Problems section is transparent on the blue page frame:
  // white text, 10% white cards and white icons are invisible without it). A template has no parent frame, so the section takes that fill.
  const rootFill = (tree.fills ?? []).some((f) => f.visible !== false && ['SOLID', 'IMAGE', 'GRADIENT_LINEAR'].includes(f.type));
  if (!rootFill && parentBg && !hand.has(tree.id)) {
    setOv(tree.id, { settings: { _background: { color: { hex: parentBg } } }, reason: `autopilot: the section is transparent in Figma, the fill ${parentBg} of its page frame shows through` });
    log('background', tree, `background ${parentBg}`, 'transparent section: the page frame fill is what the eye sees behind it', 'high');
  }

  // A picture already named the component. This pass only asks for values the tree does not have.
  const pictured = namedOnly ? new Map(det.components.filter((c) => c.status === 'approved').map((c) => [c.id, c.status])) : null;
  // ---- 1. candidates found by the rules
  for (const c of det.components) {
    if (namedOnly) {
      if (c.status !== 'approved' || isSignal(c.component)) continue;
    } else if (c.status !== 'proposed') continue;
    const node = find(tree, c.node);
    if (!node) continue;
    const tools = { ask, log, designer, formErrors, findNode: (id) => find(tree, id), textsIn, kids, hasText };
    if (!decideCandidate(c, node, tools)) {
      if (namedOnly) continue;
      c.status = 'rejected';
      c.note = `autopilot: ${c.component} needs content only the designer has`;
      log(c.component, node, 'rejected', 'needs content the Figma file does not contain', 'medium');
      needs.push(`${c.component} candidate on "${node.name}" [${node.id}] was left as blocks: ${c.evidence ?? ''}`);
    }
  }
  if (pictured) for (const c of det.components) if (pictured.has(c.id)) c.status = 'approved';

  // a checkbox or switch row is that control, not a second button, and not a field of an approved form
  const holds = (root, id) => !!root && (root.id === id || (root.children ?? []).some((c) => holds(c, id)));
  for (const choice of det.components.filter((c) => (isKind(c, PartKind.CHECKBOX) || isKind(c, PartKind.SWITCH) || isKind(c, PartKind.RADIO) || isKind(c, PartKind.SEARCH) || isKind(c, PartKind.VIDEO)) && c.status !== 'rejected')) {
    const choiceNode = find(tree, choice.node);
    for (const b of det.components.filter((c) => isKind(c, PartKind.BUTTON) && c.status !== 'rejected' && (c.node === choice.node || c.node === choice.params?.fieldNode || c.node === choice.params?.buttonNode))) {
      b.status = 'rejected';
      b.note = `autopilot: this row is a ${choice.component}, not a button`;
      for (let i = designer.length - 1; i >= 0; i--) if (designer[i].includes(`[${b.node}]`)) designer.splice(i, 1);
      for (let i = questions.length - 1; i >= 0; i--) if (questions[i].node === b.node && (questions[i].group === 'link' || questions[i].group === 'confirm')) questions.splice(i, 1);
    }
    for (const f of det.components.filter((c) => isKind(c, PartKind.FORM) && c.status === 'approved')) {
      const formNode = find(tree, f.node);
      if (formNode && choiceNode && formNode.id !== choice.node && holds(formNode, choice.node)) {
        choice.status = 'rejected';
        choice.note = 'autopilot: this control sits inside a form and stays a field of that form';
      }
    }
  }

  // a button that is the submit of an approved form is part of the form element, not a second button
  for (const f of det.components.filter((c) => isKind(c, PartKind.FORM) && c.status === 'approved')) {
    for (const b of det.components.filter((c) => isKind(c, PartKind.BUTTON) && c.status === 'approved' && c.node === f.params?.submit)) {
      b.status = 'rejected'; b.note = 'autopilot: the submit button of a form, merged into the form element';
      for (let i = questions.length - 1; i >= 0; i--) if (questions[i].group === 'link' && questions[i].node === b.node) questions.splice(i, 1); // no link to ask for: the form submits
    }
  }

  // the toggle of an approved "read more" is a <button>, not a link: nothing to ask for its URL
  for (const r of det.components.filter((c) => isKind(c, PartKind.READMORE) && c.status === 'approved')) {
    for (let i = questions.length - 1; i >= 0; i--) if (questions[i].group === 'link' && questions[i].node === r.params?.button) questions.splice(i, 1);
    for (let i = designer.length - 1; i >= 0; i--) if (designer[i].includes(`[${r.params?.button}]`)) designer.splice(i, 1);
  }

  // ---- 1b. masked decoration: a group with a mask layer and no text. CSS cannot reproduce a Figma mask, Figma can render it, so it is one picture
  if (!namedOnly) walk(tree, (n) => {
    if (n === tree || !['GROUP', 'FRAME', 'COMPONENT', 'INSTANCE'].includes(n.type) || hasText(n)) return;
    if (!kids(n).some((c) => c.isMask)) return;
    if (det.components.some((c) => isKind(c, PartKind.FLAT_IMAGE) && c.node === n.id)) return;
    det.components.push({ id: `d${Math.max(0, ...det.components.map((c) => Number(c.id.slice(1)) || 0)) + 1}`, status: 'approved', source: 'ai', component: PartKind.FLAT_IMAGE, node: n.id, level: 'E2', confidence: 'medium',
      cite: [{ node: n.id, field: 'type', equals: n.type }, { node: kids(n).find((c) => c.isMask).id, field: 'isMask', equals: true }], evidence: `${n.type} "${n.name}" holds a mask layer and no text`, params: { alt: '', link: null, scale: 2 }, note: 'autopilot: a masked decoration is rendered by Figma as one picture (CSS has no equivalent of a Figma mask)' });
    log('flat-image', n, 'approved (masked decoration)', 'contains a mask layer and no text: only Figma can render it exactly', 'high');
  });

  // ---- 2. headings
  const items = new Set((facts.repeats ?? []).flatMap((r) => r.ids));
  const inItem = (n) => { let hit = false; for (const id of items) { const it = find(tree, id); if (it && find(it, n.id)) { hit = true; break; } } return hit; };
  const styled = new Set(); // text nodes the designer already styled H1..H6
  walk(tree, (n) => { if (n.type === 'TEXT' && /^H[1-6](\b|\/)/.test(n.styleRefs?.text ?? '')) styled.add(n.id); });
  let sectionLevel = 0;
  const isNav = NAV_SECTION.test(tree.name ?? ''); // a menu has no title: its largest text is a link, not a heading
  if (!styled.size && !isNav) {
    const all = [];
    walk(tree, (n) => { if (n.type === 'TEXT' && !n.svg && n.text?.characters?.trim() && !inItem(n)) all.push(n); });
    const max = Math.max(0, ...all.map((n) => n.text.fontSize));
    const title = all.find((n) => n.text.fontSize >= max * 0.9 && n.text.characters.length <= 200);
    if (title && !hand.has(title.id)) {
      sectionLevel = firstSection ? 1 : 2;
      setOv(title.id, { element: 'heading', tag: `h${sectionLevel}`, reason: 'autopilot: the largest text of the section is its title' });
      log('heading', title, `h${sectionLevel}`, `largest text (${title.text.fontSize}px) of ${firstSection ? 'the first section of the page' : 'the section'}`, 'high');
    }
  }
  for (const r of isNav ? [] : facts.repeats ?? []) {
    for (const id of r.ids) {
      const item = find(tree, id);
      const ts = textsIn(item);
      if (ts.length < 2) continue;
      const big = ts.reduce((a, b) => (b.text.fontSize > a.text.fontSize ? b : a));
      const small = Math.min(...ts.map((t) => t.text.fontSize));
      if (big.text.fontSize >= small * 1.15 && words(big.text.characters) <= 14 && !hand.has(big.id)) {
        const level = Math.min(6, (sectionLevel || 2) + 1);
        setOv(big.id, { element: 'heading', tag: `h${level}`, reason: 'autopilot: the largest text of a repeated item is its title' });
        if (id === r.ids[0]) log('heading', big, `h${level} (every item of "${r.parentName}")`, `largest text (${big.text.fontSize}px) of each of ${r.count} repeated items`, 'medium');
      }
    }
  }

  // ---- 3. lists (base frame only: the breakpoint variants take the tags from the base frame)
  // A parent whose visible children are ALL repeated items is a list, also when the items fall into several groups of slightly different structure
  // (a menu: 5 items with a tag + 4 without).
  if (!variant && !namedOnly) {
    const byParent = new Map();
    for (const r of facts.repeats ?? []) if (r.count >= 2) { const g = byParent.get(r.parent) ?? { r, ids: new Set() }; r.ids.forEach((id) => g.ids.add(id)); byParent.set(r.parent, g); }
    for (const [pid, { r, ids }] of byParent) {
      const parent = find(tree, pid);
      if (!parent) continue;
      const exists = det.components.some((c) => isKind(c, PartKind.SEMANTIC) && c.node === parent.id);
      if (det.components.some((c) => c.node === parent.id && isAnyKind(c, ListKind) && c.status === 'approved')) continue;
      const ks = kids(parent);
      // every child is a repeated item, or every child is the same kind of thing as the first (a menu whose 10th item has a different badge)
      const all = ks.length === ids.size && ks.every((k) => ids.has(k.id)) || ks.length >= 2 && ks.every((k) => k.name === ks[0].name && k.type === ks[0].type) && [...ids].every((id) => ks.some((k) => k.id === id));
      if (all && !exists) {
        det.components.push({ id: `d${Math.max(0, ...det.components.map((c) => Number(c.id.slice(1)) || 0)) + 1}`, status: 'approved', source: 'ai', component: PartKind.SEMANTIC, node: parent.id, level: 'E2', confidence: 'medium',
          cite: [{ node: parent.id, field: 'name', equals: parent.name }], evidence: `FRAME "${parent.name}" holds ${ids.size} items of the same structure ("${r.itemName}")`, params: { tag: 'ul', itemTag: 'li' }, note: 'autopilot: a group of repeated items is a list' });
        log('list', parent, 'ul > li', `${ids.size} repeated items fill the container`, 'medium');
      } else if (!exists) needs.push(`"${parent.name}" [${parent.id}] holds ${ids.size} repeated items next to other children: left as blocks`);
    }
  }

  // ---- 3b. navigation: the label of every menu item is a link (text-link, "#" until the designer gives the URL)
  if (isNav && !namedOnly) {
    const labels = [];
    walk(tree, (n) => {
      if (!['INSTANCE', 'FRAME', 'COMPONENT'].includes(n.type) || !NAV_ITEM.test(`${n.name ?? ''} ${n.component ?? ''}`)) return;
      const ts = textsIn(n);
      if (ts.length !== 1 || hand.has(ts[0].id) || det.components.some((c) => c.node === ts[0].id)) return;
      if (det.components.some((c) => (isKind(c, PartKind.MENU) || isKind(c, PartKind.MENU_SLIDER)) && c.status === 'approved' && find(find(tree, c.node) ?? { children: [] }, ts[0].id))) return; // a label of an approved menu is built by the menu
      det.components.push({ id: `d${Math.max(0, ...det.components.map((c) => Number(c.id.slice(1)) || 0)) + 1}`, status: 'approved', source: 'ai', component: PartKind.LINK, node: ts[0].id, level: 'E2', confidence: 'medium',
        cite: [{ node: ts[0].id, field: 'type', equals: 'TEXT' }], evidence: `TEXT "${ts[0].text.characters.trim().slice(0, 40)}" is the only label of the menu item "${n.name}"`, params: { link: null }, note: 'autopilot: a menu item label is a link, "#" until the designer gives the URL' });
      labels.push(ts[0].text.characters.trim());
      ask('link', ts[0].id, `Mục menu "${ts[0].text.characters.trim().slice(0, 40)}"`);
    });
    if (labels.length) {
      log('link', tree, `${labels.length} menu item(s) are links`, `labels: ${labels.slice(0, 12).join(', ')}`, 'medium');
      designer.push(`Link URLs of the ${labels.length} menu items in "${tree.name}" (${labels.slice(0, 12).join(', ')}), written as "#"`);
    }
  }

  // ---- 4. icons and images
  let imgIndex = 0;
  walk(tree, (n) => {
    if (hand.has(n.id)) return;
    if (n.svg && n.type !== 'TEXT') {
      setOv(n.id, { settings: { _attributes: [{ name: 'aria-hidden', value: 'true' }] }, reason: 'autopilot: icon, decorative' });
    } else if (!kids(n).length && n.fills?.some((f) => f.type === 'IMAGE') && n.type !== 'TEXT') {
      imgIndex++;
      const decorative = DECOR_NAME.test(n.name);
      setOv(n.id, { alt: '', settings: { loading: firstSection ? 'eager' : 'lazy' }, reason: 'autopilot: image, alt left empty until the designer provides it' });
      if (!decorative) { designer.push(`Alt text of the image "${n.name}" [${n.id}]`); ask('alt', n.id, `Ảnh "${n.name}"`); }
    }
  });
  const nSvg = Object.values(ov.nodes).filter((v) => v.reason === 'autopilot: icon, decorative').length;
  if (nSvg) log('icons', null, `aria-hidden on ${nSvg} svg icon(s)`, 'icons are decorative unless the designer names them', 'high');
  if (imgIndex) log('images', null, `alt "" + ${firstSection ? 'eager' : 'lazy'} on ${imgIndex} image(s)`, 'alt text is content only the designer has', 'high');

  const bars = new Set();
  for (const scroll of det.components.filter((c) => isKind(c, PartKind.SCROLL))) {
    if (scroll.params?.track) bars.add(scroll.params.track);
    if (scroll.params?.thumb) bars.add(scroll.params.thumb);
  }
  for (const line of det.components.filter((c) => isKind(c, PartKind.DIVIDER) && bars.has(c.node))) {
    line.status = 'rejected';
    line.note = 'autopilot: this line is the scroll bar, not a divider';
    log('divider', find(tree, line.node) ?? tree, 'rejected (scroll bar)', line.evidence ?? '', 'high');
  }

  if (!namedOnly) {
    for (const frame of compareFrames(tree)) {
      ask('compare', frame.id, `Bảng so sánh "${frame.name || frame.id}"`);
      askRegister(frame.id, BUY_BUTTON_FIELDS, buyAttrKey);
    }
    for (const frame of priceFrames(tree)) {
      ask('price', frame.id, `Bảng giá "${frame.name || frame.id}"`);
      askRegister(frame.id);
    }
  }
  for (const item of det.components) {
    if (!isKind(item, PartKind.PRICE_TABLE) || item.status === 'rejected') continue;
    ask('price', item.node, `Bảng giá "${find(tree, item.node)?.name || item.node}"`);
    askRegister(item.node);
  }
  for (const item of det.components) {
    if (!isKind(item, PartKind.COMPARE_TABLE) || item.status === 'rejected') continue;
    ask('compare', item.node, `Bảng so sánh "${find(tree, item.node)?.name || item.node}"`);
    askRegister(item.node, BUY_BUTTON_FIELDS, buyAttrKey);
  }

  // Owner's decision (2026-11-27): every plan is a section. Header, footer and popup are made by the owner, who writes the type in the plan.
  const suggested = 'section';
  const reason = 'Mặc định là section. Header, footer, popup do chủ dự án tự chọn.';
  ask('type', tree.id, reason, suggested);
  log('template-type', tree, suggested, reason, 'high');

  ws.writeJson('detections.json', det);
  ws.writeJson('overrides.json', ov);
  return { decisions, needs, designer, questions };
}

export function writeDecisionReport(ws, { decisions, needs, designer }, title) {
  const t = (rows) => rows.length ? ['| kind | node | decision | why | confidence |', '|---|---|---|---|---|', ...rows.map((d) => `| ${d.kind} | ${d.node} | ${d.decision} | ${d.why} | ${d.confidence} |`)].join('\n') : '_none_';
  ws.writeText('decisions.md', [`# Autopilot decisions: ${title}`, '', 'Taken by rules (decide/index.mjs, policy.json), not asked. Reverse any of them by editing detections.json / overrides.json and re-running from the build step.', '', t(decisions), '', '## Left as blocks / needs a look', '', ...(needs.length ? needs.map((x) => `- ${x}`) : ['_none_']), '', '## For the designer (content the Figma file does not contain)', '', ...(designer.length ? [...new Set(designer)].map((x) => `- ${x}`) : ['_none_']), ''].join('\n'));
}
