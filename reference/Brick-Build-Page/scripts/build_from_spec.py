#!/usr/bin/env python3
"""Generate the per-template build script `scripts/build_<slug>.py` from a Figma spec.

Usage:
  python3 -m scripts.build_from_spec --slug template-foo --template-id 512
  python3 -m scripts.build_from_spec --slug template-foo --template-id 512 --force   # regenerate

The generated script owns OVERRIDES / SKIP_NODES (the only hand-edited part) and delegates
the tree to scripts/lib/spec_builder.py, so a fresh spec re-run never loses manual fixes.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from scripts.lib.figma_spec import walk  # noqa: E402

SCRIPT_TEMPLATE = '''#!/usr/bin/env python3
"""Build {name} (template {template_id}) from {spec_rel}.

Generated by scripts/build_from_spec.py — edit OVERRIDES / SKIP_NODES only.
Re-run analyze_figma_section.py to refresh the spec; this file keeps the manual fixes.

  python3 -m scripts.{module} --dry-run
  python3 -m scripts.{module}
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from scripts.lib.spec_builder import build_elements, upload_or_dump  # noqa: E402

TEMPLATE_ID = {template_id}
SPEC_JSON = ROOT / "{spec_rel}"
OUTPUT_JSON = ROOT / "scripts/refill/{short_slug}-{template_id}.json"

# Figma node id -> settings merged over the spec; value None removes the key.
OVERRIDES: dict[str, dict] = {{
{override_lines}
}}

# Figma node ids dropped from the build (decorations replaced by widgets, duplicates, ...).
SKIP_NODES: set[str] = set()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dry-run", action="store_true", help="validate + write refill JSON, no upload")
    args = parser.parse_args()
    elements = build_elements(SPEC_JSON, TEMPLATE_ID, overrides=OVERRIDES, skip=SKIP_NODES)
    return upload_or_dump(elements, TEMPLATE_ID, OUTPUT_JSON, dry_run=args.dry_run)


if __name__ == "__main__":
    raise SystemExit(main())
'''


def override_hints(payload: dict) -> list[str]:
    """Pre-fill decisions the spec flags but cannot make: page h1 and nodes carrying ⚠ notes."""
    lines: list[str] = []
    headings = [node for node in walk(payload["desktop"]) if node["role"] == "heading"]
    if headings:
        top = headings[0]
        lines.append(f'    # "{top["name"]}": section heading — switch to h1 only for the page hero (rule G4).')
        lines.append(f'    # "{top["id"]}": {{"tag": "h1"}},')
    for node in walk(payload["desktop"]):
        for note in node.get("notes", []):
            if "đã sinh" in note:
                continue
            lines.append(f'    # "{node["id"]}" {node["name"]}: ⚠ {note}')
    return lines


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--slug", required=True, help="scripts/data/<slug>/spec.json")
    parser.add_argument("--template-id", type=int, required=True)
    parser.add_argument("--force", action="store_true", help="overwrite an existing build script")
    args = parser.parse_args()

    spec_path = ROOT / "scripts" / "data" / args.slug / "spec.json"
    if not spec_path.exists():
        print(f"Missing {spec_path} — run analyze_figma_section.py first", file=sys.stderr)
        return 1
    payload = json.loads(spec_path.read_text())
    short_slug = args.slug.removeprefix("template-")
    module = "build_" + short_slug.replace("-", "_")
    target = ROOT / "scripts" / f"{module}.py"
    if target.exists() and not args.force:
        print(f"{target.relative_to(ROOT)} exists — edit it or pass --force", file=sys.stderr)
        return 1
    target.write_text(
        SCRIPT_TEMPLATE.format(
            name=payload.get("name") or args.slug,
            template_id=args.template_id,
            spec_rel=spec_path.relative_to(ROOT).as_posix(),
            short_slug=short_slug,
            module=module,
            override_lines="\n".join(override_hints(payload)),
        )
    )
    print(f"Wrote {target.relative_to(ROOT)} — review OVERRIDES, then: python3 -m scripts.{module} --dry-run")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
